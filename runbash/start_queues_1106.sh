#!/bin/bash
# 把三条"部署口径解码链"挂成排队作业（11-06 裁定：读数要按最后结果怎么产出来量，
# 所以每个资源都要走一遍 任务一判框架名称 -> 任务二发跨度 -> 任务三吃前两环产物 的完整链路）。
# 排队而不是立刻跑：白天登记卡都排了训练，解码要占 GPU，抢同一张卡会拖慢正在跑的那一格。
# 判"上一格跑完"只认链日志末尾的完成标记，不认权重文件存在。
# 标记串里有中文，所以写成文件推上去执行，不在命令行里拼（Windows 侧粘贴会乱码）。
set -e
W=/work/workspace/ccl25
cd "$W"

# 这台（${CCL25_HOST}）：容器可见编号 0=宿主机卡2、1=宿主机卡4、2=宿主机卡6
nohup bash queue_decode_1106.sh c22 0 \
    "任务一（1.0）完成=$W/chain_t1_c10_1106.log" >/dev/null 2>&1 &
echo "Q_c22_PID=$!  等 1.0 任务一跑完，用容器编号 0（宿主机卡 2）解码赛题那一格"

nohup bash queue_decode_1106.sh en 1 \
    "链 A 全部完成=$W/chain_en_1106.log" \
    "任务一（英文）完成=$W/queue_t1_en_1106.log" >/dev/null 2>&1 &
echo "Q_en_PID=$!  等英文任务三链跑完且英文任务一训完，用容器编号 1（宿主机卡 4）解码英文那一格"
